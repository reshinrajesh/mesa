/**
 * Sixteen Bengaluru venues.
 *
 * This file is the only place restaurant content lives. Screens never import
 * it: they go through `restaurantService`, which is what makes swapping in a
 * real API a one-file change.
 *
 * Every venue here is invented. The neighbourhoods, the coordinates and the
 * shape of the trading hours are real, because those are what the distance
 * line, the map and the "closed that day" state are drawn from — but the names
 * are not any real business's, and a demo dataset that borrowed one would be
 * putting words in a real restaurant's mouth.
 *
 * The dataset moved here from Lisbon when the product was scoped to India. The
 * hours are the part that carries the most local truth: a tiffin room opens at
 * half six and is shut by eight in the evening, a brewery does not open before
 * noon, and a Bengaluru kitchen closes earlier than a Lisbon one — which is
 * why the "nothing left today" state is reachable here by early evening.
 */

type DaySpec = [open: number, close: number] | null;

/** Minutes from midnight. `h(19, 30)` = 1170. */
const h = (hour: number, minute = 0) => hour * 60 + minute;

function week(spec: Record<Weekday, DaySpec>): OpeningHours[] {
  return ([0, 1, 2, 3, 4, 5, 6] as Weekday[]).map((day) => ({
    day,
    opensAt: spec[day]?.[0] ?? null,
    closesAt: spec[day]?.[1] ?? null,
  }));
}

